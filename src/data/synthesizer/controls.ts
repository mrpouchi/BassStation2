import type { ControlDefinition, ControlTarget } from '@/engine/parameters/types';

/**
 * Inventory of every physical element on the Bass Station II top panel and the
 * keyboard area. Callout numbers follow the manual's hardware overview
 * (user guide v5.0, pp. 8–12) so the inventory can be checked against it.
 */

const param = (id: string): ControlTarget => ({ param: id });

/** Shared oscillator controls route through the Osc Select switch. */
const perOsc = (suffix: string): ControlTarget => ({
  via: 'panel.oscSelect',
  routes: { osc1: param(`osc1.${suffix}`), osc2: param(`osc2.${suffix}`) },
});

const pulseWidthFor = (osc: 'osc1' | 'osc2'): ControlTarget => ({
  via: 'panel.pwSource',
  routes: {
    'mod-env': param(`${osc}.pwModEnv`),
    lfo2: param(`${osc}.pwLfo2`),
    manual: param(`${osc}.pwManual`),
  },
});

const lfoKnob = (n: 1 | 2): ControlTarget => ({
  via: 'panel.lfoDelaySpeed',
  routes: {
    delay: param(`lfo${n}.delay`),
    speed: {
      via: `lfo${n}.speedSync`,
      routes: { speed: param(`lfo${n}.speed`), sync: param(`lfo${n}.syncValue`) },
    },
  },
});

/** ADSR faders and Triggering route through Env Select. */
const perEnv = (suffix: string): ControlTarget => ({
  via: 'panel.envSelect',
  routes: {
    amp: param(`ampEnv.${suffix}`),
    mod: param(`modEnv.${suffix}`),
    both: { params: [`ampEnv.${suffix}`, `modEnv.${suffix}`] },
  },
});

const capitalize = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

