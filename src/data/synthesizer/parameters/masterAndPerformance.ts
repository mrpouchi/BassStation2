function bipolarAmount(
  id: string,
  name: string,
  key: Parameters<typeof onKey>[0],
  description: string,
  explanation: string,
  defaultValue: number,
  midi: ParameterDefinition['midi'],
  concepts: readonly string[],
  related: readonly string[],
  page: number,
): ParameterDefinition {
  return {
    id,
    name,
    section: 'modulation-matrix',
    scope: 'patch',
    access: onKey(key),
    kind: 'continuous',
    min: -63,
    max: 63,
    step: 1,
    defaultValue,
    bipolar: true,
    rangeSource: 'documented',
    description,
    education: {
      explanation,
      increase: 'Positive values: more modulation in the positive direction.',
      decrease: 'Negative values: the modulation acts in the opposite direction.',
    },
    concepts,
    related,
    midi,
    source: { page },
    visuals: [],
  };
}

